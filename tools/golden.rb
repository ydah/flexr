# frozen_string_literal: true

module FlexrVerification
  module Golden
    module_function

    def normalize(source)
      lines = source.gsub(/\r\n?/, "\n").lines
      header = lines.index("# Generated by flexr. DO NOT EDIT.\n")
      raise ArgumentError, "missing generated digest header" unless
        header && lines[header + 2]&.match?(/\A# spec-digest: sha256:[a-f0-9]{64}\n\z/)

      lines[header + 2] = "# spec-digest: <normalized>\n"
      source = lines.join
      version = compiler_version_node(source)
      normalized = source.b.dup
      normalized[version.location.start_offset...version.location.end_offset] = '"<compiler-version>"'
      normalized.force_encoding(source.encoding)
    end

    def compiler_version_node(source)
      require "prism"
      parsed = Prism.parse(source)
      raise ArgumentError, "invalid generated Ruby: #{parsed.errors.first.message}" unless parsed.errors.empty?

      pending = [parsed.value]
      installations = []
      until pending.empty?
        node = pending.pop
        if node.is_a?(Prism::CallNode) && node.name == :install_compiled! &&
            node.receiver&.slice&.delete_prefix("::") == "Flexr::Generated"
          installations << node
        end
        pending.concat(node.child_nodes.compact)
      end
      raise ArgumentError, "expected one generated installation" unless installations.length == 1

      payload = installations.first.arguments&.arguments&.[](1)
      version = hash_value(hash_value(payload, "artifact"), "compiler_version")
      raise ArgumentError, "expected a literal compiler version" unless version.is_a?(Prism::StringNode)

      version
    end

    def hash_value(node, name)
      return unless node.is_a?(Prism::HashNode)

      fields = node.elements.select do |entry|
        entry.is_a?(Prism::AssocNode) && entry.key.is_a?(Prism::SymbolNode) && entry.key.unescaped == name
      end
      fields.first.value if fields.length == 1
    end
  end
end
