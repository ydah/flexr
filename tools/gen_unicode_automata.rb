# frozen_string_literal: true

require_relative "../lib/flexr"

module UnicodeAutomataGenerator
  Unicode = Flexr::Unicode
  AST = Flexr::Regexp::AST

  class Encoder
    def initialize
      @rows = [[]]
      @states = { [] => 0 }
    end

    def encode(node)
      return [0, 0].pack("v*") if node.is_a?(AST::Fail)

      root = compile(node, 0)
      states = [root]
      ids = { root => 0 }
      edges = []
      states.each_with_index do |row, from|
        @rows.fetch(row).each do |lo, hi, target|
          to = ids[target] ||= begin
            id = states.length
            states << target
            id
          end
          edges.push(from, lo, hi, to)
        end
      end
      raise "property DFA exceeds the binary format" if states.length > 0xffff

      [states.length, ids.fetch(0), *edges].pack("v*")
    end

    private

    def compile(node, following)
      case node
      when AST::Empty then following
      when AST::ByteRange then intern([[node.lo, node.hi, following]])
      when AST::Seq
        node.children.reverse_each.reduce(following) { |successor, child| compile(child, successor) }
      when AST::Alt
        transitions = node.children.flat_map { |child| @rows.fetch(compile(child, following)) }.sort_by(&:first)
        raise "overlapping property transitions" if transitions.each_cons(2).any? { |left, right| left[1] >= right[0] }

        intern(transitions)
      else
        raise "unexpected Unicode trie node #{node.class}"
      end
    end

    def intern(transitions)
      @states[transitions] ||= begin
        id = @rows.length
        @rows << transitions
        id
      end
    end
  end

  module_function

  def generate
    names = Unicode::Data::PROPERTIES.keys.map { |name| Unicode::Property.canonical_name(name) }
    names.concat(Flexr::Regexp::Parser::POSIX_CLASSES.map { |name| "POSIX_#{name}" })
    data = +"".b
    positions = {}
    entries = names.uniq.sort.to_h do |name|
      ranges = Unicode::Property.ranges(name)
      folded = Unicode::Property.merge_ranges(ranges.flat_map { |lo, hi| Unicode::CaseFold.ranges(lo, hi) })
      complemented = Unicode::Property.complement(ranges)
      complemented_folded = Unicode::Property.complement(folded)
      variants = [ranges, folded, complemented, complemented_folded].map do |variant|
        positions[variant] ||= begin
          node = AST::CharClass.new(ranges: variant, negated: false, loc: nil)
          bytes = Encoder.new.encode(Flexr::Regexp::Normalizer.new(node).normalize)
          offset = data.bytesize
          data << bytes
          [offset, bytes.bytesize]
        end
      end
      [name, variants]
    end
    index = JSON.generate(unicode: Unicode::VERSION, properties: entries)
    bytes = Unicode::PropertyAutomata::MAGIC + [index.bytesize].pack("V") + index.b + data
    header = <<~RUBY
      # frozen_string_literal: true
      # Generated by tools/gen_unicode_automata.rb.

      module Flexr
        module Unicode
          module Data
            UTF8_AUTOMATA = <<'AUTOMATA_DATA'.unpack1("m").freeze
    RUBY
    footer = <<~RUBY
      AUTOMATA_DATA
          end
        end
      end
    RUBY
    header + [bytes].pack("m") + footer
  end
end

if $PROGRAM_NAME == __FILE__
  output = ARGV.fetch(0, Flexr::Unicode::PropertyAutomata::PATH)
  Flexr::ArtifactWriter.write!(output, UnicodeAutomataGenerator.generate)
end
