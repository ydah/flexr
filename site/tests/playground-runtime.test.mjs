import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRuntime } from '../src/playground/runtime.mjs';
import { encodeState, decodeState } from '../src/playground/share.mjs';

const binary = await readFile(new URL('../node_modules/@ruby/4.0-wasm-wasi/dist/ruby+stdlib.wasm', import.meta.url));
const assets = JSON.parse(await readFile(new URL('../public/playground-runtime/flexr.json', import.meta.url), 'utf8'));
const runtime = await createRuntime(binary, assets);

test('executes edited Ruby actions and generates a real scanner with Prism', async () => {
  const source = 'class Lexer < Flexr::Lexer\n emits :INT\n rule(/[0-9]+/) { emit :INT, text.to_i * 2 }\nend';
  const request = { source, input: '12', mode: 'runtime' };
  const result = await runtime.run(request);
  assert.deepEqual(result.tokens, [['INT', 24]]);
  assert.match(result.dot, /digraph flexr/);
  assert.equal(result.steps[0].text, '12');
  assert.match(result.generated, /Generated by flexr/);
  assert.match(result.generated, /def scan_one/);
  const generated = await runtime.run({ ...request, mode: 'generated' });
  assert.deepEqual(generated.tokens, result.tokens);
  assert.deepEqual(generated.steps, result.steps);
  assert.equal(result.ruby_version, '4.0.0');
  assert.equal(result.prism_version, '1.7.0');
});

test('renders real diagnostic source locations and rejects malformed Ruby', async () => {
  const result = await runtime.run({ source: 'class Lexer < Flexr::Lexer\n rule(/a(?=b)/, emit: :A)\nend', input: 'ab', mode: 'runtime' });
  assert.match(result.error, /FLEXR-E014/);
  assert.match(result.error, /playground.flexr.rb:2:/);
  assert.match(result.error, /\^/);
  const syntax = await runtime.run({ source: 'class Lexer <', input: '', mode: 'runtime' });
  assert.match(syntax.error, /FLEXR-E010/);
  const unmatched = await runtime.run({ source: 'class Lexer < Flexr::Lexer\n rule(/a/, emit: :A)\nend', input: 'b', mode: 'runtime' });
  assert.match(unmatched.error, /unexpected byte/);
  assert.match(unmatched.error, /input.txt:1:/);
});

test('each run starts a fresh Ruby VM', async () => {
  const source = 'class ::AbsoluteLexer < Flexr::Lexer\n rule(/a/, emit: :A)\nend';
  assert.deepEqual((await runtime.run({ source, input: 'a', mode: 'runtime' })).tokens, [['A', 'a']]);
  assert.deepEqual((await runtime.run({ source, input: 'a', mode: 'runtime' })).tokens, [['A', 'a']]);
});

test('share links retain Unicode source and input without running code', () => {
  const state = { source: 'class Lexer; # café\nend', input: '日本語', mode: 'runtime' };
  assert.deepEqual(decodeState(encodeState(state)), state);
  assert.throws(() => decodeState('x'.repeat(300_000)), /too large/);
  assert.throws(() => decodeState(btoa(JSON.stringify({ source: 5, input: '' }))), /Invalid/);
});

test('language presets use the repository examples and run in both modes', async () => {
  const presets = JSON.parse(await readFile(new URL('../public/playground-runtime/presets.json', import.meta.url), 'utf8'));
  for (const name of ['toml', 'graphql', 'sql']) {
    const preset = presets[name];
    assert.equal(preset.source, await readFile(new URL(`../../examples/${name}/lexer.flexr.rb`, import.meta.url), 'utf8'));
    const result = await runtime.run({ ...preset, mode: 'runtime' });
    assert.equal(result.error, undefined, result.error);
    assert.ok(result.tokens.length > 0);
    const generated = await runtime.run({ ...preset, mode: 'generated' });
    assert.deepEqual(generated.tokens, result.tokens);
  }
});
